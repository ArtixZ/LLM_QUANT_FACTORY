PRODUCT_BY_ID = {product.dataset_id: product for product in TUSHARE_DATA_PRODUCTS}
DEFAULT_PRODUCT_IDS = tuple(
    product.dataset_id for product in TUSHARE_DATA_PRODUCTS if product.default_enabled
)


def data_product_catalog() -> list[dict[str, object]]:
    return [product.to_dict() for product in TUSHARE_DATA_PRODUCTS]


def resolve_products(dataset_ids: list[str] | tuple[str, ...]) -> list[TushareDataProduct]:
    unknown = sorted(set(dataset_ids) - PRODUCT_BY_ID.keys())
    if unknown:
        raise ValueError(f"Unknown Tushare data products: {', '.join(unknown)}")
    return [PRODUCT_BY_ID[dataset_id] for dataset_id in dataset_ids]
