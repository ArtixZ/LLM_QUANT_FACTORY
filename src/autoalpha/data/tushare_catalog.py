from __future__ import annotations

from dataclasses import asdict, dataclass


@dataclass(frozen=True)
class TushareDataProduct:
    dataset_id: str
    api_name: str
    label: str
    category: str
    description: str
    grain: str
    cadence: str
    availability: str
    pit_policy: str
    feature_family: str
    sync_strategy: str
    date_parameter: str | None
    documentation_id: int
    default_enabled: bool = False
    panel_fields: tuple[str, ...] = ()
    integration_state: str = "CATALOG"

    def to_dict(self) -> dict[str, object]:
        value = asdict(self)
        value["documentation_url"] = (
            f"https://tushare.pro/document/2?doc_id={self.documentation_id}"
        )
        return value


